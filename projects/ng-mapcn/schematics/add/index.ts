import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import type { Rule, SchematicContext, Tree } from '@angular-devkit/schematics';
import { NodePackageInstallTask } from '@angular-devkit/schematics/tasks';

import { BARREL_HEADER, renderBarrel } from '../registry/barrel';
import { readRegistry, resolve } from '../registry/resolve';
import { addTarget, given, LEGACY_ADOPTED } from '../utils/config';
import { joinPath, normalizeTargetPath } from '../utils/path';

export interface AddOptions {
  components?: string[];
  all?: boolean;
  overwrite?: boolean;
  /** Target folder; defaults to the one saved in ng-mapcn.json by `init`, else the default. */
  path?: string;
  skipInstall?: boolean;
}

/**
 * Copies the requested components (shadcn-style) and the files they depend on into the project,
 * rewrites the `index.ts` barrel from what is present, and adds the npm dependencies they need.
 * With no components it copies the core only.
 */
export function add(options: AddOptions): Rule {
  return (tree: Tree, context: SchematicContext) => {
    // Without --path: the saved folder, an earlier copy, or an error asking to run init first.
    const explicit = given(options.path);
    const target = explicit ? { path: explicit, legacy: false } : addTarget(tree);
    const path = normalizeTargetPath(target.path);
    if (target.legacy) context.logger.warn(LEGACY_ADOPTED);
    const registry = readRegistry();
    const resolution = resolve(registry, options.components ?? [], { all: options.all });

    let created = 0;
    let overwritten = 0;
    const kept: string[] = [];
    let unchanged = 0;
    for (const file of resolution.files) {
      const target = joinPath(path, file);
      const content = readFileSync(join(__dirname, 'files', file));
      const existing = tree.exists(target) ? tree.read(target) : null;
      if (!existing) {
        tree.create(target, content);
        created++;
      } else if (sameText(existing, content)) {
        unchanged++;
      } else if (options.overwrite) {
        tree.overwrite(target, content);
        overwritten++;
      } else {
        kept.push(target);
      }
    }

    writeBarrel(
      tree,
      context,
      joinPath(path, 'index.ts'),
      renderBarrel(registry, (f) => tree.exists(joinPath(path, f))),
    );

    const added = addDependenciesWithReport(resolution.dependencies);
    added.rule(tree, context);
    const hasMaplibre = hasPackage(tree, 'maplibre-gl');
    if (!hasMaplibre) {
      context.logger.warn(
        'maplibre-gl is not in package.json. Run "npx ng-mapcn init" (or "ng add ng-mapcn") first.',
      );
    }
    if (added.names().length && !options.skipInstall) {
      context.addTask(new NodePackageInstallTask());
    }

    const names = resolution.items.join(', ');
    context.logger.info(
      `Installed: ${names}. Created ${created}, overwritten ${overwritten}, skipped ${kept.length}, unchanged ${unchanged} file(s).`,
    );
    if (kept.length) {
      context.logger.warn(
        `Kept ${kept.length} existing file(s) that differ from this version (your edits, or a copy ` +
          `from an older version):\n${kept.map((f) => `  ${f}`).join('\n')}\n` +
          'The components just copied are written against this version and may not compile with ' +
          'them. Compare them, or run again with --overwrite to replace them (your edits are lost).',
      );
    }
    if (added.names().length) {
      context.logger.info(
        `Added dependencies: ${added
          .names()
          .map((n) => `${n}@${resolution.dependencies[n]}`)
          .join(', ')}`,
      );
    }
    return tree;
  };
}

/**
 * Writes the generated barrel. One that is not ours (no generated header: hand-written, or from a
 * copy made before the header existed) is kept, with the exports it misses listed for the user.
 */
function writeBarrel(tree: Tree, context: SchematicContext, file: string, barrel: string): void {
  const existing = tree.read(file);
  if (!existing) {
    tree.create(file, barrel);
    return;
  }
  const current = existing.toString('utf8');
  if (sameText(existing, Buffer.from(barrel))) return;
  if (!current.startsWith(BARREL_HEADER)) {
    const have = new Set(current.split(/\r?\n/).map((line) => line.trim()));
    const missing = barrel
      .split('\n')
      .filter((line) => line.startsWith('export ') && !have.has(line));
    if (missing.length) {
      context.logger.warn(
        `Kept ${file}: it has no "GENERATED by ng-mapcn" header, so it may hold your own exports. ` +
          `Add these lines to it (or delete it to let add regenerate it):\n` +
          missing.map((line) => `  ${line}`).join('\n'),
      );
    }
    return;
  }
  tree.overwrite(file, barrel);
}

/** Same content, ignoring line endings (git may check copies out with CRLF). */
function sameText(a: Buffer, b: Buffer): boolean {
  if (a.equals(b)) return true;
  const text = (buffer: Buffer) => buffer.toString('utf8').replace(/\r\n/g, '\n');
  return text(a) === text(b);
}

interface DependencyRule {
  rule: Rule;
  /** Names added by the last run of `rule`. */
  names: () => string[];
}

function hasPackage(tree: Tree, name: string): boolean {
  const buffer = tree.read('package.json');
  if (!buffer) return false;
  const pkg = JSON.parse(buffer.toString());
  return Boolean(pkg.dependencies?.[name] ?? pkg.devDependencies?.[name]);
}

/**
 * Adds the given npm dependencies to `package.json`, never touching an entry the app already has
 * (in `dependencies` or `devDependencies`). `names()` reports what the rule added.
 */
export function addDependenciesWithReport(deps: Record<string, string>): DependencyRule {
  let added: string[] = [];
  const rule: Rule = (tree: Tree, context: SchematicContext) => {
    added = [];
    if (!Object.keys(deps).length) return tree;
    const buffer = tree.read('package.json');
    if (!buffer) {
      context.logger.warn(
        `package.json not found. Install: ${Object.entries(deps)
          .map(([n, v]) => `${n}@${v}`)
          .join(', ')}`,
      );
      return tree;
    }
    const pkg = JSON.parse(buffer.toString());
    pkg.dependencies = pkg.dependencies ?? {};
    for (const [name, version] of Object.entries(deps)) {
      if (!pkg.dependencies[name] && !pkg.devDependencies?.[name]) {
        pkg.dependencies[name] = version;
        added.push(name);
      }
    }
    if (added.length) tree.overwrite('package.json', JSON.stringify(pkg, null, 2) + '\n');
    return tree;
  };
  return { rule, names: () => added };
}
