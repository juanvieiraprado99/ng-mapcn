// Snapshots the component registry (name, description, dependencies) into a TS module, so the
// Installation page lists the items `ng-mapcn add` accepts. It builds the registry in memory
// instead of reading schematics/registry.json, so it never depends on the build order.
// Run before building or serving the demo (wired into build:demo and build-ui-dev).
import { writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildRegistry, realPaths } from './generate-registry.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(
  root,
  'projects',
  'demo',
  'src',
  'app',
  'pages',
  'docs',
  'registry-items.generated.ts',
);

const registry = buildRegistry(realPaths(root));

const items = Object.values(registry.items).map((item) => ({
  name: item.name,
  description: item.description.replaceAll('`', ''),
  // `core` is always copied, so listing it on every row would be noise.
  dependsOn: item.registryDependencies.filter((dep) => dep !== 'core'),
  packages: Object.keys(item.dependencies),
}));

const banner = `// GENERATED by scripts/generate-registry-docs.mjs — do not edit.
// Items accepted by \`ng-mapcn add\`, from the registry built out of the library sources.
`;
writeFileSync(
  outFile,
  `${banner}export interface RegistryItemDoc {
  name: string;
  description: string;
  /** Other items copied with this one (core is always copied). */
  dependsOn: string[];
  /** npm packages added to package.json. */
  packages: string[];
}

export const REGISTRY_ITEMS: RegistryItemDoc[] = ${JSON.stringify(items, null, 2)};\n`,
);

console.log(`Generated registry docs (${items.length} items) in ${relative(root, outFile)}`);
