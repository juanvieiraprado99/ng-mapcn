// Snapshots the component registry (name, description, dependencies) into a TS module, so the
// Installation page lists the items `ng-mapcn add` accepts. It builds the registry in memory
// instead of reading schematics/registry.json, so it never depends on the build order.
// Run before building or serving the demo (wired into build:demo and build-ui-dev).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildRegistry, realPaths } from './generate-registry.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(
  root,
  'projects',
  'demo',
  'src',
  'app',
  'pages',
  'docs',
  'registry-items.generated.ts',
);

const paths = realPaths(root);
const registry = buildRegistry(paths);

/** Absolute path of a registry file (relative to the copy root, `draw/` for the draw entry). */
const absolute = (file) =>
  file.startsWith('draw/') ? join(paths.drawDir, file.slice(5)) : join(paths.libDir, file);

/**
 * Files an item owns: its own component folder (`draw/` for draw). Core also owns the shared
 * services, providers and utils it copies, so `MapContextService` maps to core.
 */
function ownFiles(item) {
  if (item.name === 'draw') return item.files.filter((f) => f !== 'draw/index.ts');
  if (item.name === 'core')
    return item.files.filter(
      (f) => !f.startsWith('components/') || f.startsWith('components/map/'),
    );
  return item.files.filter(
    (f) => f.startsWith(`components/${item.name}/`) || f.startsWith(`components/map-${item.name}/`),
  );
}

/** Names exported by declarations in a TS source (`export class|function|const|… Name`). */
function exportedNames(source) {
  const names = new Set();
  const re =
    /^export\s+(?:declare\s+)?(?:abstract\s+)?(?:class|function|const|let|interface|type|enum)\s+([A-Za-z_$][\w$]*)/gm;
  for (const match of source.matchAll(re)) names.add(match[1]);
  return [...names].sort();
}

/** Component selectors declared in a TS source (`selector: 'ng-map-scale'`). */
function selectors(source) {
  return [...source.matchAll(/selector:\s*'([a-z][\w-]*)'/g)].map((match) => match[1]);
}

const items = Object.values(registry.items).map((item) => {
  const sources = ownFiles(item)
    .filter((f) => f.endsWith('.ts'))
    .map((f) => readFileSync(absolute(f), 'utf8'));
  return {
    name: item.name,
    description: item.description.replaceAll('`', ''),
    // `core` is always copied, so listing it on every row would be noise.
    dependsOn: item.registryDependencies.filter((dep) => dep !== 'core'),
    packages: Object.keys(item.dependencies),
    exports: [...new Set(sources.flatMap(exportedNames))].sort(),
    selectors: [...new Set(sources.flatMap(selectors))].sort(),
  };
});

const banner = `// GENERATED by scripts/generate-registry-docs.mjs — do not edit.
// Items accepted by \`ng-mapcn add\`, from the registry built out of the library sources.
`;
writeFileSync(
  outFile,
  `${banner}export interface RegistryItemDoc {
  name: string;
  description: string;
  /** Other items copied with this one (core is always copied). */
  dependsOn: string[];
  /** npm packages added to package.json. */
  packages: string[];
  /** Names the item's own files export, used to tell which items a docs snippet imports. */
  exports: string[];
  /** Element selectors of the item's components, for docs snippets that are template fragments. */
  selectors: string[];
}

export const REGISTRY_ITEMS: RegistryItemDoc[] = ${JSON.stringify(items, null, 2)};\n`,
);

console.log(`Generated registry docs (${items.length} items) in ${relative(root, outFile)}`);
