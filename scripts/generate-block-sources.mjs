// Snapshots the blocks' own source files into a TS module, so the Blocks page
// "Code" tab shows exactly the code that renders the preview. Run before
// building or serving the demo (wired into build:demo and build-ui-dev).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const blocksDir = join(root, 'projects', 'demo', 'src', 'app', 'blocks');
const outFile = join(blocksDir, 'block-sources.generated.ts');

/** Everything under a block folder; the registry and this output are not blocks. */
function collect(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return collect(path);
    return path.endsWith('.ts') ? [path] : [];
  });
}

const files = readdirSync(blocksDir)
  .map((name) => join(blocksDir, name))
  .filter((path) => statSync(path).isDirectory())
  .flatMap(collect)
  .sort();

const sources = Object.fromEntries(
  files.map((file) => [
    relative(blocksDir, file).split(sep).join('/'),
    readFileSync(file, 'utf8').replace(/\r\n/g, '\n'),
  ]),
);

const banner = `// GENERATED by scripts/generate-block-sources.mjs — do not edit.
// Source of every block file, keyed by its path inside src/app/blocks/.
`;
writeFileSync(
  outFile,
  `${banner}export const BLOCK_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};\n`,
);

console.log(`Generated block sources (${files.length} files) in ${relative(root, outFile)}`);
